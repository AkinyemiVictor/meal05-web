with garri_profile as (
  select id from public.local_measurement_profiles where code = 'garri_standard'
),
garri_products as (
  select p.id as product_id,
         base_variant.id as source_variant_id,
         base_variant.price as base_price_per_kg
  from public.products p
  left join lateral (
    select pv.id, pv.price
    from public.product_variants pv
    where pv.product_id = p.id
      and pv.is_active = true
      and lower(coalesce(pv.base_unit, '')) = 'kg'
      and pv.base_quantity = 1
      and lower(regexp_replace(trim(coalesce(pv.name, '')), '\\s+', ' ', 'g')) in ('1kg', '1 kg', 'loose kg')
    order by case when pv.purchase_mode = 'fixed' then 0 else 1 end, pv.id
    limit 1
  ) base_variant on true
  where p.is_active = true
    and lower(coalesce(p.name, '')) like '%garri%'
)
insert into public.product_measurement_settings
  (product_id, profile_id, sales_mode, calculated_pricing_enabled,
   base_price_per_kg, base_price_source_variant_id, fixed_option_discount_enabled, notes)
select gp.product_id, gpf.id, 'fixed_options', false,
       gp.base_price_per_kg, gp.source_variant_id, false,
       'Launch mode remains fixed options. Conversion metadata is stored for a later calculated-input rollout.'
from garri_products gp
cross join garri_profile gpf
on conflict (product_id) do update set
  profile_id = excluded.profile_id,
  sales_mode = 'fixed_options',
  calculated_pricing_enabled = false,
  base_price_per_kg = coalesce(public.product_measurement_settings.base_price_per_kg, excluded.base_price_per_kg),
  base_price_source_variant_id = coalesce(public.product_measurement_settings.base_price_source_variant_id, excluded.base_price_source_variant_id),
  fixed_option_discount_enabled = false,
  notes = excluded.notes,
  updated_at = now();

