create table if not exists public.local_measurement_units (
  code text primary key,
  display_name text not null,
  congo_multiplier numeric(10,4) not null check (congo_multiplier > 0),
  tin_cup_count numeric(10,2) not null check (tin_cup_count > 0),
  sort_order integer not null default 0,
  is_active boolean not null default true,
  notes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

comment on table public.local_measurement_units is
  'Reusable Nigerian local dry-goods measurement ladder. One Congo is based on ten standard milk tins.';

create table if not exists public.local_measurement_profiles (
  id bigint generated by default as identity primary key,
  code text not null unique,
  display_name text not null,
  kg_per_congo numeric(10,3) not null check (kg_per_congo > 0),
  tins_per_congo numeric(10,2) not null default 10 check (tins_per_congo > 0),
  is_active boolean not null default true,
  notes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

comment on table public.local_measurement_profiles is
  'Product-family conversion profiles used later for calculated kg-to-local-measurement ordering.';

create table if not exists public.product_measurement_settings (
  product_id bigint primary key references public.products(id) on delete cascade,
  profile_id bigint not null references public.local_measurement_profiles(id),
  sales_mode text not null default 'fixed_options'
    check (sales_mode in ('fixed_options', 'calculated_input', 'hybrid')),
  calculated_pricing_enabled boolean not null default false,
  base_price_per_kg numeric(12,2) check (base_price_per_kg is null or base_price_per_kg >= 0),
  base_price_source_variant_id bigint references public.product_variants(id) on delete set null,
  fixed_option_discount_enabled boolean not null default false,
  notes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

comment on table public.product_measurement_settings is
  'Keeps launch sales on fixed options while preserving conversion and base-price metadata for a later calculated-input system.';

